print(a)
# Добавить элемент с помощью метода .append()
a.append("Чипсы")
print(a)
# Добавить элемент с помощью сложения
a = a[:3] + ["Кока кола"] + a[3:]
print(a)
# Удаление элемента
del a[2]
print(a)
# Забрать элемент из списка
pocket = a.pop(1)
print(a)
print(pocket)
