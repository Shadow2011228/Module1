# Список - изменяемый набор элементов
a = ["Хлеб", "Молоко", "Шоколад", 23, 27.5, True]
print(a)
# Кортеж - неизменяемый набор элементов
c = ("Хлеб", "Молоко", "Шоколад", 23, 27.5, True)
print(c)
# Изменение элемента
a[1] = "Булка"
print(a)
