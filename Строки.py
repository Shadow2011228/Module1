# Строка(str) - это последовательность символов заключенная в кавычки -> ""
# У строк есть индексы(числовой идентификатор символа) от 0 до конца строки

str1 = 'hello'
print(str1)
print(str1[1]) # Взять символ по индексу
print(str1[-1]) # Взять последний символ по обратному индексу (-)
print(str1[1:4]) # Взять срез символов по индексам от и до